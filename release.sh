#!/bin/zsh
# Build a release: universal (Apple Silicon + Intel) app with an installer,
# written to updates/LTCBridge.zip + updates/latest.json. Committing and
# pushing updates/ ships it: every installed copy's "Check for Updates" reads
# latest.json from this repo on GitHub.
#   UPDATE_NOTES="What changed" ./release.sh
# (without UPDATE_NOTES the notes come from RELEASE_NOTES.txt)
set -e
cd "$(dirname "$0")"
VERSION=$(cat VERSION)
# Every error code used in the app and installer must be on the public error list.
missing=$(grep -ohE 'LB-[0-9]{3}' Sources/LTCBridge/*.swift Resources/InstallBundle.sh release.sh | sort -u | while read -r c; do
  grep -q "^| $c |" ERRORS.md || echo "$c"
done)
if [[ -n "$missing" ]]; then
  echo "Error codes missing from ERRORS.md: $missing" >&2
  exit 1
fi
./test.sh >/dev/null 2>&1 || { echo "Tests failed; run ./test.sh to see why." >&2; exit 1; }
if [[ -z "${UPDATE_NOTES:-}" && -f RELEASE_NOTES.txt ]]; then
  UPDATE_NOTES=$(<RELEASE_NOTES.txt)
fi
BUILT=$(date "+%b %d, %H:%M")
FEED="${UPDATE_FEED-https://raw.githubusercontent.com/jonpikereally/SPMTESync/main/updates/latest.json}"
cat > Sources/LTCBridge/Version.swift <<SWIFT
// Generated by build.sh / release.sh — do not edit.
enum AppVersion {
    static let version = "$VERSION"
    static let built = "$BUILT"
    static let updateFeed = "$FEED"
}
SWIFT
CACHE="${TMPDIR:-/tmp}/ltcbridge-modcache"
mkdir -p "$CACHE"
echo "Building arm64…"
swiftc -O -target arm64-apple-macos13 -module-cache-path "$CACHE" \
  -o "$CACHE/LTCBridge-arm64" Sources/LTCBridge/*.swift
echo "Building x86_64…"
swiftc -O -target x86_64-apple-macos13 -module-cache-path "$CACHE-x86" \
  -o "$CACHE/LTCBridge-x86_64" Sources/LTCBridge/*.swift

DIST="$CACHE/dist"
rm -rf "$DIST"
APP="$DIST/LTC Bridge/LTC Bridge.app"
mkdir -p "$APP/Contents/MacOS" "$APP/Contents/Resources"
lipo -create -output "$APP/Contents/MacOS/LTCBridge" "$CACHE/LTCBridge-arm64" "$CACHE/LTCBridge-x86_64"
cp Resources/Info.plist "$APP/Contents/Info.plist"
cp Resources/InstallBundle.sh "$APP/Contents/Resources/InstallBundle.sh"
/usr/libexec/PlistBuddy -c "Set :CFBundleShortVersionString $VERSION" "$APP/Contents/Info.plist"
codesign --force --sign - "$APP"

printf '#!/bin/bash\nEXPECTED_VERSION=%q\n' "$VERSION" > "$DIST/LTC Bridge/Install LTC Bridge.command"
cat >> "$DIST/LTC Bridge/Install LTC Bridge.command" <<'INSTALL'
# LTC Bridge installer — copies the app to ~/Applications and launches it.
cd "$(dirname "$0")"
fail() {
  echo
  echo "Error $1: $2"
  echo "Look up this code on the LTC Bridge error list:"
  echo "  https://github.com/jonpikereally/SPMTESync/blob/main/ERRORS.md"
  echo "(You can also give that page to an AI assistant for help.)"
  exit 1
}
echo "Installing LTC Bridge…"
mkdir -p ~/Applications || fail LB-601 "Couldn't create ~/Applications."
if /usr/bin/pgrep -x LTCBridge >/dev/null; then
  fail LB-601 "Quit LTC Bridge before running the installer, then try again."
fi
STAGE_ROOT=$(mktemp -d ~/Applications/.LTCBridge-install-XXXXXX) \
  || fail LB-601 "Couldn't create a staging folder in ~/Applications."
trap 'rm -rf "$STAGE_ROOT"' EXIT
HELPER="LTC Bridge.app/Contents/Resources/InstallBundle.sh"
cp "$HELPER" "$STAGE_ROOT/InstallBundle.sh" \
  || fail LB-601 "The download is missing its installation helper."
HELPER="$STAGE_ROOT/InstallBundle.sh"
STAGED="$STAGE_ROOT/LTC Bridge.app"
/bin/bash "$HELPER" prepare "LTC Bridge.app" "$STAGED" com.jonpike.ltcbridge "$EXPECTED_VERSION" \
  || fail LB-602 "Couldn't validate or prepare the new version. Your installed copy was kept."
/bin/bash "$HELPER" swap 0 "$STAGED" ~/Applications/"LTC Bridge.app" \
  com.jonpike.ltcbridge ~/Library/"Application Support/LTC Bridge/update-failed.txt" "$EXPECTED_VERSION" \
  || fail LB-603 "Couldn't open the replacement. Any previous working copy was kept or restored."
echo
echo "Done! Allow LTC Bridge to use the microphone when macOS asks —"
echo "that's how it hears the LTC on your audio input."
INSTALL
chmod +x "$DIST/LTC Bridge/Install LTC Bridge.command"

cat > "$DIST/LTC Bridge/README.txt" <<README
LTC Bridge v$VERSION — LTC (audio timecode) to MTC for Logic Pro, macOS 13+
https://github.com/jonpikereally/SPMTESync

INSTALL
1. Double-click "Install LTC Bridge.command".
   If macOS blocks it: right-click it, choose Open, then Open again.
2. Allow microphone access when asked — that's how it hears the LTC input.

USE
1. Pick the input device (e.g. your Dante interface or Dante Virtual
   Soundcard) and the channel carrying LTC.
2. The timecode turns green and says "Sending MTC" once it locks.
3. In Logic: Project Settings → Synchronization → Sync Mode: MTC, and
   switch on the Sync button. Logic sees the "LTC Bridge" MIDI port by itself.
"Test" generates LTC internally so you can check Logic without a source.

PRIVACY
Audio is only decoded, never recorded or sent anywhere. The only thing
LTC Bridge fetches from the internet is a small version file from the GitHub
repo above, to see whether an update exists.
README

mkdir -p updates
(cd "$DIST" && ditto -c -k --norsrc --noextattr --noqtn --keepParent "LTC Bridge" "$OLDPWD/updates/LTCBridge.zip.tmp")
mv -f updates/LTCBridge.zip.tmp updates/LTCBridge.zip
# Manifest last, so a checking app never sees it pointing at a half-written zip.
/usr/bin/python3 -c 'import json,sys; print(json.dumps({"version": sys.argv[1], "url": "LTCBridge.zip", "notes": sys.argv[2]}))' \
  "$VERSION" "${UPDATE_NOTES:-}" > updates/latest.json.tmp
mv -f updates/latest.json.tmp updates/latest.json

./build.sh >/dev/null
echo "Release v$VERSION written to updates/. Ship it with:"
echo "  git add -A && git commit -m \"Release v$VERSION\" && git push"
